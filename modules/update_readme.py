"""Regenerate the README's Model Performance block from model_metrics.json.

Only the text between the START/END markers is rewritten, so everything else
in the README stays hand-written. Run after training (the weekly workflow
does this automatically).
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
README_PATH = os.path.join(ROOT, 'README.md')
METRICS_PATH = os.path.join(ROOT, 'data', 'processed', 'model_metrics.json')
START = ('<!-- METRICS:START (auto-generated by modules/update_readme.py from '
         'data/processed/model_metrics.json; edits inside this block are overwritten) -->')
END = '<!-- METRICS:END -->'


def render(m):
    v = m['validation']
    patches = m.get('patches') or ['?', '?']
    lines = [
        f"Trained on {m['matches']:,} Ranked Solo games from patches {patches[0]}–{patches[1]}, "
        f"{m['champions']} champions (last retrained {m['trained_at']}). Validated on the "
        f"**newest {m['validation_matches']:,} matches** (time-based split: trained on older games, tested on "
        "later ones, which is the honest test for \"will this work next week\"):",
        "",
        "| Model | Log loss ↓ | AUC ↑ |",
        "|---|---|---|",
    ]
    rows = [
        ('**Full model + lane matchup evidence (shipped)**', 'full_model_plus_lane_evidence', True),
        ('Full model, no lane evidence', 'full_model', False),
        ('Without enemy terms (ablation)', 'allies_only_ablation', False),
        ('No draft information (side bias only)', 'baseline_side_only', False),
    ]
    for label, key, bold in rows:
        if key in v:
            ll, auc = f"{v[key]['log_loss']:.4f}", f"{v[key]['auc']:.3f}"
            lines.append(f"| {label} | {'**' + ll + '**' if bold else ll} | {'**' + auc + '**' if bold else auc} |")

    dq = m.get('decision_quality')
    if dq:
        lines += [
            "",
            "### Do the recommendations point to winning picks?",
            f"For every player in the {m['validation_matches']:,} held-out games, the champion they actually played "
            "was ranked among all options for their role, given the other nine champions, by a model trained only "
            "on older games:",
            "",
            "| Where the model ranked the champion they played | Picks | Won |",
            "|---|---|---|",
            f"| **Model's top 5** | {dq['top5']['picks']:,} | **{dq['top5']['won']:.1%}** |",
        ]
        for label, key in (('Top third', 'top_third'), ('Middle third', 'middle_third'), ('Bottom third', 'bottom_third')):
            b = dq[key]
            lines.append(f"| {label} | {b['picks']:,} | {b['won']:.1%} (±{b['ci95'] * 100:.1f}) |")
        lines += [
            "",
            "Picks the model favors win more often, by a few points rather than a landslide. Only "
            f"{dq['share_of_picks_in_top5']:.0%} of real high-Elo picks fall in the model's top 5: players mostly pick "
            "from their own champion pool, which is why the app shows a separate **From your pool** row.",
        ]

    cal = m.get('calibration')
    if cal:
        lines += [
            "",
            "### Are the win percentages honest?",
            "Scored from both teams' perspectives (so the blue/red side effect cancels), on held-out games, after "
            "calibration:",
            "",
            "| Model predicted | Actually won | Games |",
            "|---|---|---|",
        ]
        lines += [f"| {a['predicted']:.1%} | {a['actual']:.1%} | {a['n']:,} |" for a in cal['after']]
        lines += [
            "",
            f"The calibration temperature (currently {cal['temperature']:.2f}; 1.00 means no adjustment, above 1 "
            "softens overconfident predictions, below 1 sharpens underconfident ones) is re-fitted on held-out "
            "games at every weekly retrain and applied to the win % users see.",
        ]

    lines += [
        "",
        "### Notes",
        "- These numbers are regenerated automatically by the weekly pipeline after each retrain.",
        "- Hyperparameters, shrinkage strengths, recency half-life and the composition features were chosen by "
        "rolling time-based validation, averaged over several random seeds where effects are small.",
        "- Draft-only prediction is a low-signal problem (player skill and execution dominate at high Elo), so the "
        "model's job is to rank picks by a few points of win probability, not to call games. Picks within 0.5 "
        "points of the best are shown as tied, since the model can't reliably separate smaller gaps.",
    ]
    return "\n".join(lines)


def update(readme_path=README_PATH, metrics_path=METRICS_PATH):
    """Rewrite the marked block. Returns True if the README changed."""
    with open(metrics_path, encoding='utf-8') as f:
        metrics = json.load(f)
    with open(readme_path, encoding='utf-8') as f:
        text = f.read()
    if text.count(START) != 1 or text.count(END) != 1 or text.index(START) > text.index(END):
        raise ValueError(f'{readme_path} must contain exactly one START and one END metrics marker, in order.')
    head, rest = text.split(START)
    _, tail = rest.split(END)
    new = f"{head}{START}\n{render(metrics)}\n{END}{tail}"
    if new != text:
        with open(readme_path, 'w', encoding='utf-8', newline='\n') as f:
            f.write(new)
    return new != text


if __name__ == '__main__':
    sys.stdout.reconfigure(encoding='utf-8')
    print('README metrics updated.' if update() else 'README metrics already up to date.')
